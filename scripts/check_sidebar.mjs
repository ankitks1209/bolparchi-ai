import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = createRequire(import.meta.url)(process.argv[2] || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
page.setDefaultTimeout(4000);
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.argv[3] || 'http://127.0.0.1:8766');
  assert.equal(await page.getByRole('button', { name: 'Open sidebar', exact: true }).count(), 1, 'The sheet logo is an operable sidebar button');
  const toggle = page.getByRole('button', { name: 'Open sidebar', exact: true });
  assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(await toggle.locator('.brand-mark').evaluate(el => getComputedStyle(el).transform), 'none');
  await toggle.click();
  const drawer = page.getByRole('dialog', { name: 'Workspace' });
  await drawer.waitFor();
  assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('#sidebar .brand-mark')).transform !== 'none');
  await page.getByRole('button', { name: 'Choose a job', exact: true }).click();
  await drawer.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Start update', exact: true }).click();
  await page.getByLabel('Your update').fill('Unsubmitted text stays here');
  const before = await page.locator('#reference').textContent();
  let writes = 0;
  page.on('request', request => { if (request.method() === 'POST') writes++; });
  await toggle.click();
  await page.getByRole('button', { name: 'Review the record', exact: true }).click();
  await drawer.waitFor({ state: 'hidden' });
  assert.equal(await page.getByLabel('Your update').inputValue(), 'Unsubmitted text stays here');
  assert.equal(await page.locator('#reference').textContent(), before);
  assert.equal(await page.evaluate(() => document.activeElement.id), 'review-title');
  await toggle.click();
  await page.keyboard.press('Escape');
  await drawer.waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => document.activeElement.id), 'sidebar-toggle');
  await toggle.click();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(() => document.querySelector('#sidebar').contains(document.activeElement)), true, 'Focus stays in the modal sidebar');
  await page.mouse.click(800, 400);
  await drawer.waitFor({ state: 'hidden' });
  await mkdir('artifacts/browser', { recursive: true });
  for (const width of [1280, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await toggle.click();
    await page.waitForFunction(() => !document.querySelector('#sidebar').getAnimations().some(animation => animation.playState === 'running'));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await drawer.evaluate(el => el.scrollWidth <= el.clientWidth), true);
    await page.screenshot({ path: `artifacts/browser/sidebar-${width}.png` });
    await page.getByRole('button', { name: 'Close sidebar', exact: true }).click();
    await drawer.waitFor({ state: 'hidden' });
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await toggle.click();
  assert.equal(await drawer.evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.keyboard.press('Escape');
  await drawer.waitFor({ state: 'hidden' });
  assert.equal(writes, 0, 'Sidebar navigation never submits, saves or cancels a draft');
  assert.deepEqual(errors, []);
  console.log('PASS: straight/tilted logo toggle, contextual sidebar shortcuts, no lost input or writes, Escape/backdrop/close, focus containment/return, reduced motion and 1280/390/320 layouts.');
} finally { await browser.close(); }
